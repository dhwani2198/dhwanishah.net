import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';

const output=resolve(import.meta.dirname,'../output/qa');
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'no-preference'});
await page.goto('http://127.0.0.1:4187/');
await page.waitForFunction(()=>document.querySelector('#home-scene video').videoWidth===3840);
await page.mouse.move(710,380);
await page.mouse.move(755,395,{steps:10});
await page.waitForTimeout(250);
await page.screenshot({path:resolve(output,'home-cursor-sparks.png')});
await page.screenshot({path:resolve(output,'cursor-sparks-detail.png'),clip:{x:690,y:350,width:110,height:100}});
await page.getByRole('link',{name:'About',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('#about-scene video').videoWidth===3840);
await page.mouse.move(710,380);
await page.mouse.move(755,395,{steps:10});
await page.waitForTimeout(250);
await page.screenshot({path:resolve(output,'about-cursor-sparks.png')});
const painted=()=>page.locator('.about-sparks').evaluate(canvas=>{const pixels=canvas.getContext('2d').getImageData(0,0,canvas.width,canvas.height).data;return pixels.some((value,index)=>index%4===3&&value>0);});
assert.equal(await painted(),true,'Sparks appear on the About animation');
await page.screenshot({path:resolve(output,'about-cursor-sparks-detail.png'),clip:{x:690,y:350,width:110,height:100}});
await page.locator('.home-link').screenshot({path:resolve(output,'home-arrow-detail.png')});
await page.locator('.about-read').click();
await page.mouse.move(710,380);
await page.waitForTimeout(250);
await page.screenshot({path:resolve(output,'about-biography-no-sparks.png')});
assert.equal(await painted(),false,'No sparks appear on the About biography');
await page.locator('.connect').scrollIntoViewIfNeeded();
await page.waitForTimeout(1600);
const contact=await page.locator('.connect').boundingBox();
await page.mouse.move(contact.x+20,contact.y+30);
await page.waitForTimeout(250);
await page.screenshot({path:resolve(output,'say-hello-without-halo.png')});
assert.equal(await painted(),false,'No sparks appear around Say hello');
await page.emulateMedia({reducedMotion:'reduce'});
await page.locator('.about-back').screenshot({path:resolve(output,'back-arrow-detail.png')});
await page.goto('http://127.0.0.1:4187/sprint-x');
const carousel=page.frameLocator('.published-case').locator('.native-carousel');
await carousel.scrollIntoViewIfNeeded();
await page.frameLocator('.published-case').getByRole('button',{name:'Next',exact:true}).screenshot({path:resolve(output,'carousel-arrow-detail.png')});
await browser.close();
console.log(`Reviewed cursor sparks and navigation arrows in ${output}`);
