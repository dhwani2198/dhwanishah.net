import { chromium, webkit, devices } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';

const output=resolve(import.meta.dirname,'../output/qa');
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'reduce'});
await page.goto('http://127.0.0.1:4187/');
await page.locator('#home-scene .scene-poster').evaluate(img=>img.decode());
await page.screenshot({path:resolve(output,'home-desktop.png')});
await page.getByRole('link',{name:'View projects',exact:true}).click();
await page.locator('.project-list [data-project="topnotch"]').hover();
await page.locator('.preview-original').evaluate(img=>img.decode());
await page.screenshot({path:resolve(output,'projects-topnotch-desktop.png')});
await page.locator('.preview-original').click();
await page.locator('.teaser-media img').evaluate(img=>img.decode());
await page.screenshot({path:resolve(output,'topnotch-preview-desktop.png')});
await page.getByRole('button',{name:'Close project viewer'}).click();
await page.locator('.project-list [data-project="sprint-x"]').hover();
await page.locator('.preview-panel .preview-original').evaluate(img=>img.decode());
await page.screenshot({path:resolve(output,'projects-desktop.png')});
await page.locator('.project-list [data-project="curalink"]').hover();
await page.locator('.preview-original').evaluate(img=>img.decode());
await page.screenshot({path:resolve(output,'projects-curalink-desktop.png')});
await page.locator('.project-list [data-project="sprint-x"]').hover();
await page.locator('.preview-original').evaluate(img=>img.decode());
await page.locator('.preview-open').click();
await page.frameLocator('.published-case').locator('img').first().evaluate(img=>img.decode());
await page.screenshot({path:resolve(output,'viewer-desktop.png')});
await page.goto('http://127.0.0.1:4187/about');
await page.locator('#about-scene .scene-poster').evaluate(img=>img.decode());
await page.screenshot({path:resolve(output,'about-animation-desktop.png')});
await page.locator('.about-read').click();
await page.screenshot({path:resolve(output,'about-story-desktop.png')});
await page.locator('.art-grid').scrollIntoViewIfNeeded();
await page.locator('.art-grid img').last().evaluate(img=>img.decode());
await page.screenshot({path:resolve(output,'about-artwork-desktop.png')});
await browser.close();
